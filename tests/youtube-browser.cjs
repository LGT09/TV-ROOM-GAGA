const {chromium}=require("@playwright/test")
const assert=require("node:assert/strict")
const fs=require("node:fs")
;(async()=>{
  const browser=await chromium.launch({executablePath:"/repl/tools/bin/chromium",headless:true,args:["--no-sandbox"]})
  try {
    const context=await browser.newContext({viewport:{width:390,height:844},reducedMotion:"reduce"})
    const page=await context.newPage()
    page.setDefaultTimeout(35000)
    const errors=[]
    page.on("pageerror",e=>errors.push(e.message))
    await page.goto(`https://${process.env.REPLIT_DEV_DOMAIN}/downloader`,{waitUntil:"domcontentloaded"})
    const input=page.getByRole("textbox",{name:"YouTube link or search terms"})
    await input.fill("Adele Hello")
    await page.getByRole("button",{name:"Search",exact:true}).click()
    await page.getByRole("heading",{name:"Search results",exact:true}).waitFor()
    assert.ok(await page.getByRole("button",{pressed:true}).count()>0)
    await input.fill("https://youtu.be/YQHsXMglC9A")
    await page.getByRole("button",{name:"Search",exact:true}).click()
    await page.getByRole("button",{name:"Play full audio",exact:true}).waitFor()
    await page.getByRole("button",{name:"Play full audio",exact:true}).click()
    await page.waitForFunction(()=>document.querySelector("audio")?.duration>120,undefined,{timeout:45000})
    await page.locator("audio").evaluate(a=>a.play())
    await page.waitForFunction(()=>document.querySelector("audio")?.currentTime>.5)
    const audio=await page.locator("audio").evaluate(a=>({duration:a.duration,time:a.currentTime,src:new URL(a.src).pathname}))
    await page.locator("audio").evaluate(a=>a.pause())
    await page.getByRole("button",{name:"Download full audio",exact:true}).click()
    const save=page.getByRole("link",{name:"Save file",exact:true})
    await save.waitFor()
    const url=await save.getAttribute("href")
    const file=await context.request.get(new URL(url,page.url()).href,{headers:{Range:"bytes=0-1023"}})
    assert.equal(file.status(),206)
    assert.match(file.headers()["content-disposition"],/attachment/)
    assert.equal((await file.body()).length,1024)
    await page.getByRole("button",{name:"Watch video",exact:true}).click()
    await page.waitForFunction(()=>{const v=document.querySelector("video");return v&&v.videoWidth>0&&v.duration>120},undefined,{timeout:45000})
    await page.locator("video").evaluate(v=>v.play())
    await page.waitForFunction(()=>document.querySelector("video")?.currentTime>.5)
    const video=await page.locator("video").evaluate(v=>({duration:v.duration,width:v.videoWidth,height:v.videoHeight,time:v.currentTime,src:new URL(v.src).pathname}))
    await page.getByText("TV ROOM GAGA",{exact:true}).first().waitFor()
    for(const width of [320,768,1440]){
      await page.setViewportSize({width,height:900})
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`No horizontal overflow at ${width}`)
    }
    fs.mkdirSync("generated-artifacts",{recursive:true})
    await page.setViewportSize({width:390,height:844})
    await page.locator("video").evaluate(v=>{v.pause();v.closest(".space-y-3").scrollIntoView({block:"center"})})
    await page.screenshot({path:"generated-artifacts/youtube-tools-mobile.png"})
    console.log(JSON.stringify({keywordSearch:true,pastedLinkSearch:true,audio,video,downloadBytes:1024,responsive:[320,768,1440],errors},null,2))
    assert.deepEqual(errors,[])
  }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)})
