const {chromium}=require("@playwright/test")
const assert=require("node:assert/strict")
const fs=require("node:fs")
const base=`https://${process.env.REPLIT_DEV_DOMAIN}`
;(async()=>{
 fs.mkdirSync("generated-artifacts",{recursive:true})
 const browser=await chromium.launch({executablePath:"/repl/tools/bin/chromium",args:["--no-sandbox"]})
 const context=await browser.newContext({viewport:{width:390,height:844}})
 const errors=[],results=[]
 context.on("page",p=>p.on("pageerror",e=>errors.push(e.message)))
 try{
  const catalogue=await context.request.get(base+"/api/library?action=list&q=Avatar&limit=12")
  const data=await catalogue.json()
  assert.equal(catalogue.status(),200,JSON.stringify(data))
  const avatar=data.items.find(i=>i.title==="Avatar"&&(String(i.year).startsWith("2009")||!i.year))
  assert.ok(avatar,"Actual Avatar record must be returned")
  const home=await context.newPage()
  await home.route("**/api/library?**",route=>{
   if(new URL(route.request().url()).searchParams.get("action")==="list")
    return route.fulfill({json:{success:true,items:[avatar],page:1,limit:12,hasNext:false}})
   return route.continue()
  })
  await home.goto(base+"/home")
  await home.getByRole("heading",{name:"Trending songs",exact:true}).waitFor({timeout:20000})
  await home.getByRole("button",{name:"Open Avatar",exact:true}).click()
  const sourceResponse=await home.waitForResponse(r=>r.url().includes("/api/library?")&&new URL(r.url()).searchParams.get("action")==="stream",{timeout:40000})
  const media=await sourceResponse.json()
  assert.equal(sourceResponse.status(),200,JSON.stringify(media))
  assert.ok(media.sources.some(s=>s.downloadUrl))
  const video=home.locator("video").first()
  await video.waitFor()
  await home.waitForFunction(()=>{const v=document.querySelector("video");return v&&v.videoWidth>0},{timeout:35000})
  await video.evaluate(v=>v.play())
  await home.waitForFunction(()=>document.querySelector("video")?.currentTime>.4,{timeout:15000})
  const playing=await video.evaluate(v=>({width:v.videoWidth,height:v.videoHeight,time:v.currentTime,src:new URL(v.currentSrc).pathname}))
  assert.equal(playing.src,"/api/media")
  await home.locator("[data-media-watermark]").waitFor()
  const file=await context.request.get(base+media.sources.find(s=>s.downloadUrl).downloadUrl,{headers:{Range:"bytes=0-1023"},timeout:20000})
  assert.equal(file.status(),206)
  assert.match(file.headers()["content-type"],/video/)
  assert.match(file.headers()["content-disposition"],/attachment/)
  assert.equal((await file.body()).length,1024)
  results.push({flow:"actual Home card → title lookup → inline movie playback → ranged file download",playing,downloadBytes:1024})
  await video.evaluate(v=>v.pause())
  await home.getByRole("textbox",{name:"Search songs or artists",exact:true}).fill("Adele")
  await home.getByRole("textbox",{name:"Search songs or artists",exact:true}).press("Enter")
  await home.waitForResponse(r=>r.url().includes("/api/music?")&&r.url().includes("action=search"),{timeout:20000})
  await home.getByRole("button",{name:"Reset to trending songs"}).click()
  for(const width of [320,768,1440]){
   await home.setViewportSize({width,height:900})
   assert.ok(await home.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`Home overflows ${width}`)
  }
  await home.setViewportSize({width:390,height:844})
  await home.screenshot({path:"generated-artifacts/home-songs.png",fullPage:true})
  await home.getByRole("heading",{name:"Trending songs",exact:true}).scrollIntoViewIfNeeded()
  await home.screenshot({path:"generated-artifacts/home-music-390.png"})
  results.push({flow:"Home trending/search/reset and responsive 320/768/1440",result:"passed"})
  const tv=await context.newPage();await tv.goto(base+"/live-tv")
  await tv.getByRole("textbox",{name:"Search public channels"}).fill("Jazeera")
  await tv.getByRole("button",{name:"Search",exact:true}).click()
  await tv.getByRole("button").filter({hasText:"Al Jazeera"}).first().click({timeout:45000})
  await tv.locator("video").waitFor({timeout:15000})
  await tv.waitForFunction(()=>document.querySelector("video")?.videoWidth>0,{timeout:35000})
  await tv.locator("video").evaluate(v=>v.play())
  await tv.waitForFunction(()=>document.querySelector("video")?.currentTime>.4,{timeout:15000})
  const live=await tv.locator("video").evaluate(v=>({width:v.videoWidth,height:v.videoHeight,time:v.currentTime}))
  assert.ok((await tv.locator("video").getAttribute("src")).startsWith("blob:")||(await tv.locator("video").getAttribute("src")).startsWith("/api/tv-stream"))
  await tv.locator("[data-media-watermark]").waitFor()
  results.push({flow:"real TV through same-origin HLS relay",playing:live})
  assert.deepEqual(errors,[])
  console.log(JSON.stringify({results,errors},null,2))
  fs.writeFileSync("generated-artifacts/source-fixes-results.json",JSON.stringify({results,errors},null,2))
 }finally{await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
